"""Refs #607. Offline reconstruction of ADV-REGRESSION-001 from pinned Git objects.
Alternatively use exact source copies from the owner archive. Synthetic evidence only.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import check_adversarial as audit

GRAMMAR = 'tools/experimental/grammar-452-scoped-clauses/'
ADVERSARIAL = 'tools/experimental/adversarial-448-jitter-alphabets/'
PINS = {'binding': '3aa52100c32f10b89638db67193608e8fe9b04b6', 'overlap': '5efb84b938c2bf69f11ef3c5864221f041077c3b'}
MANIFESTS = {'binding': '4817287dd72ad4994fd57359f6596b4899ec1f72bbb0f84e170271e7318d5487', 'overlap': '4f0e768b50133ea110977faea13d7cae51d41e6830aead3b8cbf351aa5035f0d'}
AUDIT_SHA = '7305352143d2ebe6fd91e9e2d0630a470a8ab1edd575efd6e4c33b63bb0b92d2'
CHECKER_SHA = 'a1b8e37fc31096bbd25196d2731b8cd2e62aed6165d70d59006d4266cb4fe0f2'


def encoded(obj):
    return (json.dumps(obj, indent=2) + '\n').encode('utf-8')


def copy_sources(root, repo, source_root):
    for kind, (_, script, generator_blob, grammar_pin) in audit.SPECS.items():
        dest = root / kind
        dest.mkdir()
        inventory = {name: (grammar_pin, GRAMMAR, blob) for name, blob in audit.COMMON.items()}
        if kind == 'overlap':
            inventory['competing-starts'] = (grammar_pin, GRAMMAR, 'af3f673f28e65bb4fc241a22cc603a6cbb041dfb')
        inventory[script] = (PINS[kind], ADVERSARIAL, generator_blob)
        for name, (ref, prefix, blob) in sorted(inventory.items()):
            filename = name + '.py'
            if repo is not None:
                data = subprocess.check_output(['git', '-C', str(repo), 'show', ref + ':' + prefix + filename])
            else:
                data = (source_root / kind / filename).read_bytes()
            audit.require(audit.blob(data) == blob, kind + '/' + filename + ' frozen Git blob mismatch')
            (dest / filename).write_bytes(data)


def verify_frozen_output(folder, expected):
    manifest = json.loads((folder / 'manifest.json').read_text(encoding='utf-8'))
    files = sorted(p for p in folder.iterdir() if p.name != 'manifest.json')
    audit.require(all(p.is_file() and not p.is_symlink() for p in files), 'non-file output')
    audit.require(manifest == {p.name: audit.sha(p.read_bytes()) for p in files}, 'raw output manifest mismatch')
    # Preserve original generated bytes. Compare canonical LF text only for cross-platform reference.
    normalized = {}
    for p in files:
        data = p.read_bytes()
        if p.suffix in ('.html', '.json', '.jsonl'):
            data = data.replace(b'\r\n', b'\n')
        normalized[p.name] = audit.sha(data)
    audit.require(audit.sha(encoded(normalized)) == expected, 'frozen generated output differs beyond CRLF')
    return len(files) + 1


def build(root, repo, source_root):
    checker = Path(audit.__file__).resolve()
    audit.require(audit.sha(checker.read_bytes()) == CHECKER_SHA, 'checker differs from frozen Run 020')
    copy_sources(root, repo, source_root)
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE='1', PYTHONUTF8='1')
    total = 0
    for kind, (sub, script, _, _) in audit.SPECS.items():
        base = root / kind
        subprocess.run([sys.executable, str(base / (script + '.py')), str(base), str(base / sub)], env=env, check=True)
        total += verify_frozen_output(base / sub, MANIFESTS[kind])
    shutil.copyfile(checker, root / 'check_adversarial.py')
    shutil.copyfile(Path(__file__), root / 'build_adversarial.py')
    data = subprocess.check_output([sys.executable, str(root / 'check_adversarial.py'), str(root)], env=env).replace(b'\r\n', b'\n')
    audit.require(audit.sha(data) == AUDIT_SHA, 'independent audit differs from Run 020')
    (root / 'audit.json').write_bytes(data)
    (root / 'README.txt').write_bytes(b'MHAC ADV-REGRESSION-001 / Refs #607\nSynthetic only. Open index.html offline. No autoplay; start with low hardware volume.\nOriginal galleries use 20% digital gain; no SPL or RMS matching claim.\nRebuild: python build_adversarial.py NEW_DIR --source-root .\nOr use --repo PATH to a Git clone containing the four immutable commits in PINS and audit.SPECS.\nPython 3.13.5 / NumPy 2.3.5 reference. Original lane attribution retained. No new license grant.\nAll other experiments excluded. Original boundary README is not a build input.\nWindows and physical audition not yet qualified.\n')
    (root / 'index.html').write_bytes(b'<!doctype html><html lang="en"><meta charset="utf-8"><title>MHAC Adversarial Regression 001</title><h1>MHAC Adversarial Regression 001</h1><p>Synthetic evidence only. Start at low hardware volume. Original galleries: opt-in audio, 20% digital gain.</p><ul><li><a href="binding/boundary1/index.html">Source-binding boundary</a></li><li><a href="overlap/overlap1/index.html">Overlapping framing boundaries</a></li></ul><p><a href="audit.json">Independent audit</a> | <a href="README.txt">Instructions</a> | <a href="manifest.json">Hashes</a></p></html>')
    files = sorted(p for p in root.rglob('*') if p.is_file())
    (root / 'manifest.json').write_bytes(encoded({p.relative_to(root).as_posix(): audit.sha(p.read_bytes()) for p in files}))
    print(f'PASS: 21 frozen source instances, {total} frozen generated files (LF-normalized text only), frozen independent audit; {len(files)+1} package files')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--repo', type=Path)
    group.add_argument('--source-root', type=Path)
    args = parser.parse_args()
    output = args.output.resolve()
    audit.require(not output.exists(), 'output already exists')
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='mhac-adv-', dir=output.parent) as temp:
        root = Path(temp) / 'package'
        root.mkdir()
        build(root, args.repo, args.source_root)
        audit.require(not output.exists(), 'output appeared during build')
        root.rename(output)


if __name__ == '__main__':
    main()
